"""COMPARISON_V5B.csv: one row per (system, split, operating point) for every V5b
evaluation that exists as a saved artifact. Generated from artifacts, never typed.
Adapted from scripts/v4/make_transfer_csv.py.

Sources (all read-only):
  * reports/v5b/test/matched_fp_sdistest.json            H2 pyro-sdis TEST, matched neg-image FP
  * reports/v5b/tables/T8c_*.md                          H2 rows for systems absent from the JSON (seeds, v4a_s2)
  * reports/v5b/tables/T8b_*.md, T8d_*.md, T8e_*.md      H1 / H3 / H4 recall at the pre-registered VAL confs
  * reports/v5b/test/dino_holdout_recall_at_sdisval_thresholds.json  DINO components on H1/H3 (v4 sdis-val confs)
  * reports/v5b/val/matched_fp_{sdisval,borealval,firemanval}{,_seeds}.json and
    reports/v5b/val/matched_fp_S5_ensemble_v4a_s2_sdisval.json         VAL matched-FP tables
H3 (sheffieldholdout) rows are flagged contaminated=True for arms whose corpus holds Sheffield
(S2_B*, S3_C, S4_D, S4b_D2, S4c_D3; LOCKBOX_V5B_FROZEN.md) - exactly as T8d marks them.

Usage: .venv/bin/python scripts/v5b/make_comparison_csv_v5b.py [--out reports/v5b/COMPARISON_V5B.csv]
"""
import argparse, csv, glob, json, re
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--out", default="reports/v5b/COMPARISON_V5B.csv")
a = ap.parse_args()

COLS = ["system", "split", "regime", "operating_point", "conf", "recall", "tiny_recall",
        "precision", "n_images", "n_neg", "contaminated", "source_json"]
H2_NAME = {"expE": "S0_expE", "expB": "S0b_expB", "A": "S1_A", "B": "S2_B", "C": "S3_C", "D": "S4_D",
           "D2": "S4b_D2", "D3": "S4c_D3", "S5ens": "S5_ensemble_v4a_s2", "B6": "v4B6_lora_Hplus"}
CONTAMINATED_H3 = re.compile(r"^(S2_B|S3_C|S4_D|S4b_D2|S4c_D3)")
rows, seen = [], set()


def add(r):
    key = (r["system"], r["split"], r["regime"], r["operating_point"])
    if key in seen:
        return
    seen.add(key)
    rows.append({c: r.get(c, "") for c in COLS})


def fmt(x):
    return "" if x is None else x


# 1. H2 matched-FP JSON (the headline test artifact)
f = "reports/v5b/test/matched_fp_sdistest.json"
d = json.load(open(f))
for sysname, m in d["models"].items():
    for op, v in d["matched_fp"][sysname].items():
        add(dict(system=H2_NAME.get(sysname, sysname), split="sdistest", regime="matched-FP",
                 operating_point=f"negFP={op[2:]}", conf=v["conf"], recall=v["recall"],
                 tiny_recall=fmt(v.get("tiny_recall")), precision=v["precision"],
                 n_images=m["n_images"], n_neg=m["n_negative_images"], contaminated=False, source_json=f))

# 2. T8 tables (generated by make_report_tables_v5b.py from the test parquets)
CELL_MFP = re.compile(r"c=([\d.]+) R ([\d.]+) / tiny ([\d.n/a]+) / P ([\d.]+)")
CELL_RC = re.compile(r"c=([\d.]+) R ([\d.]+) \(tiny ([\d.n/a]+)")
DENOM = re.compile(r"([\d,]+) imgs / ([\d,]+) neg")


def parse_table(path, split, regime, op_names, cell_re):
    for line in open(path):
        if not line.startswith("| ") or line.startswith("| system"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        sysname = cells[0].replace("**CONTAMINATED**", "").strip()
        dm = DENOM.search(cells[-1])
        if not dm:
            continue
        n_img, n_neg = int(dm.group(1).replace(",", "")), int(dm.group(2).replace(",", ""))
        contaminated = bool(split == "sheffieldholdout" and (CONTAMINATED_H3.match(sysname) or "CONTAMINATED" in cells[0]))
        for op, cell in zip(op_names, cells[1:1 + len(op_names)]):
            m = cell_re.search(cell)
            if not m:
                continue
            tiny = "" if m.group(3).startswith("n/a") else float(m.group(3))
            prec = float(m.group(4)) if cell_re is CELL_MFP else ""
            add(dict(system=sysname, split=split, regime=regime, operating_point=op, conf=float(m.group(1)),
                     recall=float(m.group(2)), tiny_recall=tiny, precision=prec, n_images=n_img, n_neg=n_neg,
                     contaminated=contaminated, source_json=path))


T8 = {k: sorted(glob.glob(f"reports/v5b/tables/T8{k}_*.md"))[0] for k in "bcde"}
MFP_OPS = ["negFP=0.01", "negFP=0.02", "negFP=0.05", "negFP=0.10", "negFP=0.20"]
RC_OPS = ["sdisval-negFP=0.05", "sdisval-negFP=0.10", "sdisval-negFP=0.20", "firemanval-negFP=0.05", "firemanval-negFP=0.10"]
parse_table(T8["c"], "sdistest", "matched-FP", MFP_OPS, CELL_MFP)
parse_table(T8["b"], "firemanholdout", "recall-at-VAL-conf", RC_OPS, CELL_RC)
parse_table(T8["d"], "sheffieldholdout", "recall-at-VAL-conf", RC_OPS, CELL_RC)
# T8e holds two tables (boreal ruokolahti, AuSmoke forest) in one file; split on the bold headers
txt = open(T8["e"]).read()
for split, marker in [("borealtest", "**H4 boreal ruokolahti TEST"), ("foresttest", "**H4 AuSmoke forest TEST")]:
    seg = txt.split(marker, 1)[1].split("\n**", 1)[0].split("\nSources:", 1)[0]
    tmp = Path("/tmp/_t8e_" + split + ".md"); tmp.write_text(seg)
    parse_table(str(tmp), split, "recall-at-VAL-conf", RC_OPS, CELL_RC)
    # overwrite the source path with the real table
    for r in rows:
        if r["source_json"] == str(tmp):
            r["source_json"] = T8["e"]

# 3. DINO components on the two new holdouts (v4 sdis-val confs; recall only)
f = "reports/v5b/test/dino_holdout_recall_at_sdisval_thresholds.json"
d = json.load(open(f))
for run, v in d["runs"].items():
    for split in ["firemanholdout", "sheffieldholdout"]:
        for lvl, x in v[split]["at"].items():
            add(dict(system=run, split=split, regime="recall-at-VAL-conf(v4 sdis-val)",
                     operating_point="sdisval-negFP=0." + lvl.replace("negfp_", "").replace("pct", "").zfill(2),
                     conf=x["conf"], recall=x["box_recall"], tiny_recall=fmt(x.get("tiny_recall")), precision="",
                     n_images=v[split]["n_images"], n_neg=v[split]["n_neg"], contaminated=False, source_json=f))

# 4. VAL matched-FP tables (selection evidence)
for f in sorted(glob.glob("reports/v5b/val/matched_fp_*.json")):
    stem = Path(f).stem.replace("matched_fp_", "")
    split = stem.replace("_seeds", "").replace("_baselines", "")
    if stem.startswith("S5_ensemble"):
        split = "sdisval"
    d = json.load(open(f))
    for sysname, m in d["models"].items():
        name = {"S5_ensemble": "S5_ensemble_v4a_s2", "yolo_A": "v4a_s2", "dino_B6": "v4B6_lora_Hplus",
                "expE": "S0_expE", "expB": "S0b_expB"}.get(sysname, sysname)
        for op, v in d.get("matched_fp", {}).get(sysname, {}).items():
            add(dict(system=name, split=split, regime="matched-FP", operating_point=f"negFP={op[2:]}",
                     conf=v["conf"], recall=v["recall"], tiny_recall=fmt(v.get("tiny_recall")), precision=v["precision"],
                     n_images=m["n_images"], n_neg=m["n_negative_images"], contaminated=False, source_json=f))

rows.sort(key=lambda r: (r["split"], r["system"], r["regime"], r["operating_point"]))
with open(a.out, "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=COLS); w.writeheader(); w.writerows(rows)
print(f"{len(rows)} rows -> {a.out}")
