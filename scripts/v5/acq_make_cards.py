import cv2
ROOT = Path('/local/home/tianrgua/cvproject/data/v5/raw')
NOW = datetime.datetime.utcnow().strftime('%Y-%m-%dT%H:%MZ')

def logs(d):
    p = ROOT/d/'_download_log.jsonl'
    return [json.loads(l) for l in open(p)] if p.exists() else []

def probe_video(p):
    cap = cv2.VideoCapture(str(p))
    if not cap.isOpened(): return None
    fps = cap.get(cv2.CAP_PROP_FPS); n = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH)); h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    ok, _ = cap.read(); cap.release()
    return dict(fps=round(fps,3), frames=n, dur_s=round(n/fps,1) if fps else None, w=w, h=h, decodable=bool(ok))

def file_table(d, probe=True):
    rows = ['| file | bytes | sha256 (first 16) | md5 check | probe |', '|---|---|---|---|---|']
    tot = 0
    for r in logs(d):
        p = ROOT/d/r['file']; tot += r['bytes']
        pr = ''
        if probe and p.suffix.lower() in ('.mp4','.webm','.mov','.avi','.mts'):
            v = probe_video(p); pr = f"{v['w']}x{v['h']} @ {v['fps']} fps, {v['frames']} fr, {v['dur_s']} s, decodable={v['decodable']}" if v else 'cv2: cannot open'
        md5s = 'match' if (r.get('md5') and r['md5'] in r['url'] + str(logs)) else ('n/a' if not r.get('md5') else 'see log')
        rows.append(f"| {r['file']} | {r['bytes']:,} | {r['sha256'][:16]} | {'md5 ' + r['md5'][:8] if r.get('md5') else 'none published'} | {pr} |")
    return '\n'.join(rows), tot

def zip_summary(p, maxnames=12):
    try:
        z = zipfile.ZipFile(p); names = z.namelist()
        exts = {}
        for n in names: exts[os.path.splitext(n)[1].lower()] = exts.get(os.path.splitext(n)[1].lower(), 0) + 1
        return len(names), exts, names[:maxnames], sum(i.file_size for i in z.infolist())
    except Exception as e:
        return None, {'error': str(e)}, [], 0

def write(d, text):
    (ROOT/d).mkdir(parents=True, exist_ok=True)
    (ROOT/d/'CARD.md').write_text(text); print('wrote', ROOT/d/'CARD.md')

