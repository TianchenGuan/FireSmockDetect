"""Write data CARDs for V5 Day-1 acquisition downloads (data/v5/raw/<source>/CARD.md).
Facts come from _download_log.jsonl (size/sha256/md5/url), cv2 probing of videos, and
zip listings. Static provenance/licence text is embedded here verbatim from the fetched
landing pages (see reports/v5/ACQUISITION_LEADS_V5.md for the fetch record)."""
import json, os, sys, zipfile, re, datetime
